#!/usr/bin/env bash
# Original standalone Quartus 17 resource probe. No RBF or board deployment.
set -euo pipefail
main() {
  local root mode quartus_bin build path result half_bit
  root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
  mode="${1:---check}"
  [[ $# -le 1 && ( "$mode" == --check || "$mode" == --build ) ]] || {
    echo 'usage: probe_z_kanji_cache_quartus.sh [--check|--build]' >&2; return 2;
  }
  half_bit="${CACHE_HALF_BIT:--1}"
  [[ "$half_bit" =~ ^(-1|[0-9]|[12][0-9]|3[01])$ ]] || {
    echo 'CACHE_HALF_BIT must be -1 (caller) or 0..31 (descriptor bit).' >&2; return 2;
  }
  quartus_bin="${QUARTUS_BIN:-/home/alans/intelFPGA_lite/17.0/quartus/bin}"
  for path in quartus_sh quartus_map quartus_fit; do [[ -x "$quartus_bin/$path" ]]; done
  [[ "$("$quartus_bin/quartus_sh" --version)" == *'Version 17.0'* ]]
  for path in kanji_cache.qpf kanji_cache.qsf kanji_cache.sdc; do
    [[ -f "$root/verilator/tests/quartus/z_kanji_cache/$path" ]]
  done
  [[ -f "$root/rtl/x1_z_kanji_cache.sv" ]]
  [[ "$mode" == --build ]] || { echo 'Preflight passed; no probe started.'; return; }
  if pgrep -x 'quartus_(sh|map|fit|asm|sta)' >/dev/null; then
    echo 'Quartus is already running; preserve foreign jobs before starting a probe.' >&2; return 1;
  fi
  mkdir -p "$root/output_files"
  build="$(mktemp -d "$root/output_files/z-kanji-cache-probe-XXXXXXXX")"
  cp "$root/rtl/x1_z_kanji_cache.sv" "$build/"
  cp "$root/verilator/tests/quartus/z_kanji_cache/"kanji_cache.{qpf,qsf,sdc} "$build/"
  cp "$build/kanji_cache.qsf" "$build/source_kanji_cache.qsf"
  printf '\n# Explicit standalone probe profile, generated by the frozen script.\nset_parameter -entity x1_z_kanji_cache -name VID_DESCRIPTOR_HALF_BIT %s\n' \
    "$half_bit" >> "$build/kanji_cache.qsf"
  cp "$root/scripts/probe_z_kanji_cache_quartus.sh" "$build/"
  cmp "$root/rtl/x1_z_kanji_cache.sv" "$build/x1_z_kanji_cache.sv"
  (
    cd "$build"
    sha256sum x1_z_kanji_cache.sv kanji_cache.qpf source_kanji_cache.qsf kanji_cache.qsf kanji_cache.sdc \
      probe_z_kanji_cache_quartus.sh > input.sha256
  )
  {
    printf '%s\n' "host=$(hostname)" "started_utc=$(date -u +%FT%TZ)" \
      "descriptor_half_bit=$half_bit" \
      'scope=standalone dual-slot cache storage inference/fit; no board/timing acceptance'
    "$quartus_bin/quartus_sh" --version
    sha256sum "$build/input.sha256"
  } > "$build/probe-manifest.txt"
  printf 'Probe snapshot: %s\n' "$build"
  export PATH="$quartus_bin:$PATH"
  cd "$build"
  set +e
  quartus_map --parallel=2 --write_settings_files=off kanji_cache > map.log 2>&1
  result=$?
  if [[ $result -eq 0 ]]; then
    quartus_fit --parallel=2 --write_settings_files=off kanji_cache > fit.log 2>&1
    result=$?
  fi
  set -e
  printf '%s\n' "finished_utc=$(date -u +%FT%TZ)" "exit_status=$result" >> probe-manifest.txt
  sha256sum -c input.sha256 > input-after.txt
  printf 'Evidence: %s\n' "$build"
  return "$result"
}
main "$@"
